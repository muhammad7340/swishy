#!/usr/bin/env python3
"""Generate the procedural aquarium decor models.

  models/seashell_01..03   ribbed scallop / cockle shells, 5-8 cm, white/cream
  models/starfish          five-armed star, 12 cm across, pink-purple
  models/backdrop          painted blue backdrop on the inside of the back glass

All are soft decor: no collision and visibility_flags 8, so the gpu_lidar
(whose visibility_mask excludes 0x8) never sees them while the robot camera
and the GUI do. Colours are chosen outside the color detector's HSV ranges
(object_detection_node.py): cream/white are far below its saturation limits,
the starfish hue (~H 163) sits between its blue (100-140) and red (0-10)
ranges, and the backdrop keeps saturation below the blue range's S >= 150.

Usage:
    python3 scripts/make_decor_assets.py
"""
import colorsys
import math
import os

import numpy as np
from PIL import Image

MODELS = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                      "..", "src", "fishy_fish_navigation", "models")

# Back glass and water, from the tank mesh / aquarium_water (fish_world.sdf)
BACK_GLASS_Y = 1.77
GLASS_HALF_X = 1.865
WATER_Z = 1.6
BACKDROP_BOTTOM_Z = 0.80   # just below the sand at the back (0.86-1.03)


def lin(c):
    """sRGB 0..1 -> linear, for .mtl Kd values (Gazebo treats Kd as linear)."""
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def kd(rgb255):
    return " ".join(f"{lin(c / 255):.4f}" for c in rgb255)


def vertex_normals(verts, faces):
    """Area-weighted smooth normals; Gazebo lights OBJs by their vn records."""
    v = np.asarray(verts, float)
    n = np.zeros_like(v)
    for a, b, c in faces:
        fn = np.cross(v[b] - v[a], v[c] - v[a])
        n[a] += fn
        n[b] += fn
        n[c] += fn
    length = np.linalg.norm(n, axis=1, keepdims=True)
    n = np.where(length > 1e-12, n / np.maximum(length, 1e-12), [0.0, 0.0, 1.0])
    return n


def write_obj(path, verts, uvs, faces, mtl_name=None):
    normals = vertex_normals(verts, faces)
    with open(path, "w") as f:
        if mtl_name:
            f.write(f"mtllib {os.path.basename(path)[:-4]}.mtl\nusemtl {mtl_name}\n")
        for v in verts:
            f.write("v {:.5f} {:.5f} {:.5f}\n".format(*v))
        for t in uvs:
            f.write("vt {:.5f} {:.5f}\n".format(*t))
        for nv in normals:
            f.write("vn {:.4f} {:.4f} {:.4f}\n".format(*nv))
        for a, b, c in faces:
            f.write(f"f {a + 1}/{a + 1}/{a + 1} {b + 1}/{b + 1}/{b + 1} {c + 1}/{c + 1}/{c + 1}\n")


def write_mtl(path, name, rgb255, specular=0.15):
    with open(path, "w") as f:
        f.write(f"newmtl {name}\nKa 0 0 0\nKd {kd(rgb255)}\n"
                f"Ks {specular} {specular} {specular}\nNs 40\nd 1\n")


def grid_faces(n_u, n_v, offset=0, flip=False):
    faces = []
    for i in range(n_u):
        for j in range(n_v):
            a = offset + i * (n_v + 1) + j
            b, c, d = a + n_v + 1, a + n_v + 2, a + 1
            if flip:
                faces += [(a, c, b), (a, d, c)]
            else:
                faces += [(a, b, c), (a, c, d)]
    return faces


def write_model(name, description, visual, extra_comment=""):
    d = os.path.join(MODELS, name)
    with open(os.path.join(d, "model.config"), "w") as f:
        f.write(f'''<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.8">model.sdf</sdf>
  <description>
    {description}
    Generated by scripts/make_decor_assets.py.
  </description>
</model>
''')
    with open(os.path.join(d, "model.sdf"), "w") as f:
        f.write(f'''<?xml version="1.0"?>
<!-- {name}: {description}
     Generated by scripts/make_decor_assets.py.
     Soft decor: no collision; visibility_flags 8 keeps it out of the gpu_lidar.{extra_comment} -->
<sdf version="1.8">
  <model name="{name}">
    <static>true</static>
    <link name="link">
{visual}
    </link>
  </model>
</sdf>
''')


def mesh_visual(mesh, cast_shadows=True):
    return f'''      <visual name="visual">
        <geometry>
          <mesh><uri>meshes/{mesh}</uri></mesh>
        </geometry>
        <cast_shadows>{"true" if cast_shadows else "false"}</cast_shadows>
        <visibility_flags>8</visibility_flags>
      </visual>'''


def shell(name, length, height, ribs, fan_deg, rgb255, desc):
    """Scallop-like fan: a ribbed dome over a flat base, hinge at the origin
    side, lying on the sand (z = 0)."""
    n_u, n_v = 24, 64
    half = math.radians(fan_deg) / 2
    top, uvs = [], []
    for i in range(n_u + 1):
        u = i / n_u                                   # 0 at hinge .. 1 at rim
        for j in range(n_v + 1):
            v = -half + 2 * half * j / n_v
            r = length * (0.12 + 0.88 * u)
            rib = 0.5 + 0.5 * math.cos(ribs * (v + half) / (2 * half) * 2 * math.pi)
            z = height * math.sqrt(max(0.0, 1 - u ** 2)) * (0.85 + 0.15 * rib) * \
                (1 - (abs(v) / half) ** 4) + 0.002 * rib * u
            top.append((r * math.sin(v), r * math.cos(v) - length / 2, z))
            uvs.append((u, j / n_v))
    base = [(x, y, 0.0) for x, y, _ in top]
    verts = top + base
    faces = grid_faces(n_u, n_v) + grid_faces(n_u, n_v, offset=len(top), flip=True)
    d = os.path.join(MODELS, name, "meshes")
    os.makedirs(d, exist_ok=True)
    write_obj(os.path.join(d, "shell.obj"), verts, uvs + uvs, faces, "Shell")
    write_mtl(os.path.join(d, "shell.mtl"), "Shell", rgb255)
    write_model(name, desc, mesh_visual("shell.obj"))


def starfish(name, across, height, rgb255):
    n_r, n_a = 16, 160
    R = across / 2
    top, uvs = [], []
    for i in range(n_r + 1):
        u = i / n_r
        for j in range(n_a + 1):
            a = 2 * math.pi * j / n_a
            # five arms: outline radius swings between the body and the arm tips
            lobe = abs(math.cos(2.5 * a)) ** 1.6
            rr = R * (0.32 + 0.68 * lobe) * u
            # slight dome, plus small bumps along the arms
            z = height * (1 - u ** 2) * (0.6 + 0.4 * lobe) + \
                0.0012 * math.sin(40 * u) * lobe * (1 - u)
            top.append((rr * math.cos(a), rr * math.sin(a), z))
            uvs.append((u, j / n_a))
    base = [(x, y, 0.0) for x, y, _ in top]
    faces = grid_faces(n_r, n_a) + grid_faces(n_r, n_a, offset=len(top), flip=True)
    d = os.path.join(MODELS, name, "meshes")
    os.makedirs(d, exist_ok=True)
    write_obj(os.path.join(d, "starfish.obj"), top + base, uvs + uvs, faces, "Starfish")
    write_mtl(os.path.join(d, "starfish.mtl"), "Starfish", rgb255, specular=0.25)
    h, s, v = colorsys.rgb_to_hsv(*(c / 255 for c in rgb255))
    write_model(name, f"Five-armed starfish, {across * 100:.0f} cm across, pink-purple "
                f"(OpenCV H {h * 180:.0f}, S {s * 255:.0f}).", mesh_visual("starfish.obj"))


def backdrop(name):
    d = os.path.join(MODELS, name)
    os.makedirs(os.path.join(d, "meshes"), exist_ok=True)
    os.makedirs(os.path.join(d, "materials", "textures"), exist_ok=True)

    # 2048 x 1024 vertical gradient, deep blue at the bottom to lighter
    # teal-blue at the top, with faint soft vertical light streaks.
    # Saturation stays <= ~120 (OpenCV scale) so the detector's blue range
    # (S >= 150) never matches.
    W, H = 2048, 1024
    bottom = np.array([40, 58, 74], float)    # deep, muted navy
    top_c = np.array([84, 124, 140], float)   # lighter teal-blue
    t = (1 - np.arange(H) / (H - 1))[:, None, None] ** 1.3  # 1 at top row
    img = bottom + (top_c - bottom) * t
    img = np.broadcast_to(img, (H, W, 3)).copy()
    rng = np.random.default_rng(5)
    x = np.arange(W)
    streaks = np.zeros(W)
    for _ in range(14):
        c, w, a = rng.uniform(0, W), rng.uniform(25, 90), rng.uniform(4, 10)
        streaks += a * np.exp(-0.5 * ((x - c) / w) ** 2)
    fade = np.linspace(1.0, 0.15, H)[:, None]               # strongest near the top
    img += (streaks[None, :] * fade)[..., None]          # neutral: brighter, not bluer
    img = np.clip(img, 0, 255).astype(np.uint8)
    Image.fromarray(img, "RGB").save(os.path.join(d, "materials", "textures", "backdrop.png"),
                                     optimize=True)
    hsv = np.asarray(Image.fromarray(img).convert("HSV"))
    s_max = int(hsv[..., 1].max())

    # A single quad in the model frame: x across, z up, facing -y (into the tank).
    half_w = GLASS_HALF_X - 0.005
    hgt = WATER_Z - BACKDROP_BOTTOM_Z
    verts = [(-half_w, 0, 0), (half_w, 0, 0), (half_w, 0, hgt), (-half_w, 0, hgt)]
    uvs = [(0, 0), (1, 0), (1, 1), (0, 1)]
    # counter-clockwise when seen from -y
    write_obj(os.path.join(d, "meshes", "backdrop.obj"), verts, uvs, [(0, 1, 2), (0, 2, 3)])
    visual = f'''      <visual name="visual">
        <geometry>
          <mesh><uri>meshes/backdrop.obj</uri></mesh>
        </geometry>
        <cast_shadows>false</cast_shadows>
        <material>
          <diffuse>1 1 1 1</diffuse>
          <specular>0 0 0 1</specular>
          <!-- a little self-lighting so the painted backdrop stays visible
               although it faces away from the sun -->
          <emissive>0.15 0.15 0.15 1</emissive>
          <pbr>
            <metal>
              <albedo_map>materials/textures/backdrop.png</albedo_map>
              <emissive_map>materials/textures/backdrop.png</emissive_map>
              <roughness>1</roughness>
              <metalness>0</metalness>
            </metal>
          </pbr>
        </material>
        <visibility_flags>8</visibility_flags>
      </visual>'''
    write_model(name, f"Painted blue backdrop on the inside of the back glass, "
                f"{2 * half_w:.2f} x {hgt:.2f} m; model origin = bottom centre, facing -y.",
                visual, f"\n     Texture saturation max S {s_max} (detector blue needs S >= 150).")
    return s_max


if __name__ == "__main__":
    shell("seashell_01", 0.075, 0.018, 9, 150, (238, 230, 214), "Ribbed scallop shell, 7.5 cm, cream.")
    shell("seashell_02", 0.055, 0.015, 7, 135, (246, 244, 240), "Ribbed scallop shell, 5.5 cm, white.")
    shell("seashell_03", 0.065, 0.024, 13, 110, (236, 218, 212), "Ribbed cockle shell, 6.5 cm, pinkish cream.")
    starfish("starfish", 0.12, 0.012, (196, 92, 168))
    s = backdrop("backdrop")
    print(f"wrote seashell_01..03, starfish, backdrop (backdrop max S = {s})")
